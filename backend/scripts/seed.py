# (job index, candidate index, application status)
APPLICATIONS = [
    (0, 0, "Shortlisted"),
    (0, 1, "Under Review"),
    (0, 2, "New"),
    (1, 3, "Shortlisted"),
    (1, 4, "New"),
]


def remove_existing_demo_data(db: Session, user: Profile) -> None:
    db.execute(delete(Job).where(Job.user_id == user.id, Job.title.startswith(DEMO_PREFIX)))
    db.execute(
        delete(Candidate).where(Candidate.user_id == user.id, Candidate.name.endswith("(Sample)"))
    )


def seed(db: Session, user: Profile) -> None:
    remove_existing_demo_data(db, user)

    jobs = [Job(user_id=user.id, **job) for job in JOBS]
    db.add_all(jobs)
    candidates = [
        Candidate(
            user_id=user.id,
            name=data.name,
            email=data.email,
            phone=data.phone,
            location=data.location,
            linkedin_url=data.linkedin_url,
            github_url=data.github_url,
            summary=data.summary,
        )
        for data in CANDIDATES
    ]
    db.add_all(candidates)
    db.flush()

    for job_index, candidate_index, status in APPLICATIONS:
        job, candidate, data = (
            jobs[job_index],
            candidates[candidate_index],
            CANDIDATES[candidate_index],
        )
        resume = Resume(
            candidate_id=candidate.id,
            job_id=job.id,
            file_name="sample-resume.pdf",
            file_url="demo/no-file",
            file_type="pdf",
            content_hash=hashlib.sha256(f"demo:{job.id}:{candidate.id}".encode()).hexdigest(),
            raw_text=DEMO_SUMMARY,
            parsed_data=data.model_dump(),
            processing_status="completed",
        )
        db.add(resume)
        db.flush()

        application = Application(
            candidate_id=candidate.id, job_id=job.id, resume_id=resume.id, status=status
        )
        db.add(application)
        db.flush()

        requirements = job_parser.effective_requirements(job)
        breakdown = scoring_service.score_candidate(
            data, requirements, job_parser.build_job_text(job, requirements)
        )
        db.add(
            ScreeningResult(
                application_id=application.id,
                **breakdown.model_dump(),
                ai_score=NEUTRAL_AI_SCORE,
                overall_score=scoring_service.calculate_overall_score(breakdown, NEUTRAL_AI_SCORE),
                ai_summary=DEMO_SUMMARY,
                strengths=[],
                weaknesses=[],
                recommendation=None,
            )
        )
    db.commit()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--email", required=True, help="Email of a recruiter who has logged in.")
    args = parser.parse_args()

    with SessionLocal() as db:
        user = db.scalar(select(Profile).where(Profile.email == args.email))
        if user is None:
            sys.exit(f"No profile for {args.email}. Log in to the app once, then run this again.")
        seed(db, user)
    print(f"Loaded {len(JOBS)} demo jobs and {len(CANDIDATES)} demo candidates.")


if __name__ == "__main__":
    main()
